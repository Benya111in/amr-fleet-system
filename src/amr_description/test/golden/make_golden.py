#!/usr/bin/env python3
"""
기본 구성 URDF 골든 파일 생성기 (test_urdf_golden.py 가 대조한다).

골든은 "3D LiDAR 를 넣기 전(origin/develop d8ae80c)의 xacro 가 내던 URDF" 를 바이트 그대로 담는다.
설정은 같은 디렉터리의 config/ (그 시점의 최상위 config/robot_params.yaml·sensors.yaml 사본)으로 고정하므로
최상위 config/ 가 나중에 바뀌어도 이 대조는 xacro 변경만 본다. 같은 방식으로 spawn.launch.py 가 만드는
parameter_bridge 항목도 bridge_default.yaml / bridge_odom_tf.yaml 로 남긴다 (launch 패키지가 있어야 한다).

xacro 판에 따라 맨 앞에 붙는 "autogenerated by xacro from <절대 경로>" 머리 주석(경로가 환경마다 다르다)이 있으면
그것만 지운다. Humble xacro 는 표준 출력에 이 주석을 붙이지 않았다 (2026-10-06 amr-ai/rl:0.3 실측) — 그 경우 바이트 그대로다.

    # amr_description 소스 트리(빌드 없이)로 골든을 다시 만든다 — 기본 구성의 URDF 를 일부러 바꿨을 때만
    python3 make_golden.py --pkg <amr_description 디렉터리> --out <출력 디렉터리>
"""

import argparse
import importlib.util
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

import yaml

HERE = Path(__file__).resolve().parent

#: (이름, xacro 인자). fleet_* 는 multi_robot.launch.py 기본 5대 (launch_utils.description_action 이 주는 인자)
VARIANTS = (
    ('single_default', {}),
    *[(f'fleet_amr_0{i}', {'robot_name': f'amr_0{i}', 'prefix': f'amr_0{i}/'})
      for i in range(1, 6)],
    ('payload_large_amr_02', {'robot_name': 'amr_02', 'prefix': 'amr_02/', 'payload': 'large'}),
    ('runtime_payload_off', {'runtime_payload': 'false'}),
)

_AUTOGEN = re.compile(r'<!-- =+ -->\n<!-- \| +This document was autogenerated by xacro from .*'
                      r' +\| -->\n<!-- \| +EDITING THIS FILE BY HAND IS NOT RECOMMENDED +\| -->\n'
                      r'<!-- =+ -->\n')


def strip_autogen(text: str) -> str:
    """Xacro 머리 주석(절대 경로 포함) 4줄을 지운다. 없으면 그대로."""
    return _AUTOGEN.sub('', text, count=1)


def run_xacro(xacro_file: Path, config_dir: Path, args: dict, env=None) -> str:
    """Xacro 전개 결과 (머리 주석 제거)."""
    cmd = ['xacro', str(xacro_file), f'config_dir:={config_dir}']
    cmd += [f'{k}:={v}' for k, v in args.items()]
    r = subprocess.run(cmd, capture_output=True, text=True, check=False, env=env)
    if r.returncode != 0:
        raise RuntimeError(f'xacro 실패 ({" ".join(cmd)}): {r.stderr}')
    return strip_autogen(r.stdout)


def fake_prefix_env(pkg: Path, tmp: Path) -> dict:
    """$(find amr_description) 가 pkg 를 가리키게 하는 임시 ament 접두어."""
    index = tmp / 'share' / 'ament_index' / 'resource_index' / 'packages'
    index.mkdir(parents=True)
    (index / 'amr_description').write_text('', encoding='utf-8')
    os.symlink(pkg, tmp / 'share' / 'amr_description')
    env = dict(os.environ)
    env['AMENT_PREFIX_PATH'] = f'{tmp}:{env.get("AMENT_PREFIX_PATH", "")}'.rstrip(':')
    return env


def bridge_goldens(pkg: Path) -> dict:
    """{파일 이름: spawn.launch.py _bridge_entries 결과} — 고정 sensors.yaml 기준."""
    sys.path.insert(0, str(pkg))          # 새 트리의 amr_description 모듈 (옛 트리에는 없다)
    spec = importlib.util.spec_from_file_location('spawn_launch',
                                                  pkg / 'launch' / 'spawn.launch.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    with open(HERE / 'config' / 'sensors.yaml', encoding='utf-8') as f:
        sensors = yaml.safe_load(f)['/**']['ros__parameters']
    return {'bridge_default.yaml': mod._bridge_entries(sensors, False),
            'bridge_odom_tf.yaml': mod._bridge_entries(sensors, True)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--pkg', type=Path, required=True, help='amr_description 소스 디렉터리')
    ap.add_argument('--out', type=Path, default=HERE)
    ns = ap.parse_args(argv)
    pkg = ns.pkg.resolve()
    with tempfile.TemporaryDirectory() as tmp:
        env = fake_prefix_env(pkg, Path(tmp))
        for name, args in VARIANTS:
            text = run_xacro(pkg / 'urdf' / 'amr.urdf.xacro', HERE / 'config', args, env)
            (ns.out / f'{name}.urdf').write_text(text, encoding='utf-8')
            print(f'{name}: {len(text.encode())} B')
    for name, entries in bridge_goldens(pkg).items():
        with open(ns.out / name, 'w', encoding='utf-8') as f:
            yaml.safe_dump(entries, f, sort_keys=False)
        print(f'{name}: {len(entries)} 항목')
    return 0


if __name__ == '__main__':
    sys.exit(main())
